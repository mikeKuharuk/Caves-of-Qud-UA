# Small helpers

def base_name(example_name: str) -> str:
    """'Strings.Conversations.example.xml' -> 'Strings.Conversations'; 'HistorySpice.jsonc' -> 'HistorySpice'"""
    return example_name.removesuffix(".example.xml").removesuffix(".jsonc")


def is_spice(example_name: str) -> bool:
    return example_name.endswith(".jsonc")


def po_name(example_name: str) -> str:
    """'Strings.Conversations.example.xml' -> 'Strings.Conversations.po'"""
    return base_name(example_name) + ".po"


def output_name(example_name: str, lang: str = "uk") -> str:
    if is_spice(example_name):
        # HistoricSpice.Init merges mod files whose name starts with "historyspice."
        return f"{base_name(example_name).lower()}.{lang}.json"
    return base_name(example_name) + f".{lang}.xml"


def game_build(xml_text: str) -> str | None:
    """The build number from the generated header comment, e.g. '2.0.212.31'."""
    m = BUILD_RE.search(xml_text[:600])
    return m.group(1) if m else None


def unindent(text: str) -> str:
    """What the game does to XML text nodes (TextBuilder.Unindent): trim the whole text, then
    drop leading whitespace of every line, and remove carriage returns."""
    text = text.replace("\r", "").strip()
    return "\n".join(line.lstrip() for line in text.split("\n"))


def is_unit(value: str | None) -> bool:
    return value is not None and MARK in value


def is_compound(value: str) -> bool:
    """More than one marker, or a marker that is not at the start ('key,key,▶text')."""
    return value.count(MARK) > 1 or not value.startswith(MARK)


def strip_marks(value: str) -> str:
    return value.replace(MARK, "")


# syllables of the name generator: "true" there is a syllable of Templar Mecha names, not a boolean
NAME_PARTS = {"prefix", "infix", "postfix"}


def excluded(tag: str, attr: str, value: str, name: str | None = None) -> bool:
    boolean = strip_marks(value).strip() in EXCLUDED_VALUES and tag not in NAME_PARTS
    return ((tag, attr) in EXCLUDED_ATTRS or boolean
            or (tag in ("tag", "stag", "property") and attr == "Value" and name in EXCLUDED_TAG_NAMES))


def parse_schema(xml_text: str) -> dict[str, tuple[str, ...]]:
    """Key attributes per element tag, from the header comment the game generates."""
    m = re.search(r"<!--(.*?)-->", xml_text, re.S)
    schema: dict[str, list[str]] = {}
    if not m:
        return {}
    for tm in SCHEMA_TAG.finditer(m.group(1)):
        tag = tm.group(1)
        keys = schema.setdefault(tag, [])
        for am in SCHEMA_ATTR.finditer(tm.group(2)):
            if "Key" in am.group(2).split(",") and am.group(1) not in keys:
                keys.append(am.group(1))
    return {t: tuple(k) for t, k in schema.items()}


def _attr_msgid(value: str) -> tuple[str, bool]:
    compound = is_compound(value)
    return (value if compound else value[1:]), compound


def _text_msgid(text: str) -> tuple[str, bool]:
    t = unindent(text)
    compound = is_compound(t)
    if not compound:
        t = unindent(t[1:])
    return t, compound


def _has_text_unit(el: ET.Element) -> bool:
    return is_unit(el.text) and bool((el.text or "").strip())


def is_template(el: ET.Element) -> bool:
    """A ▶-marked template element with child elements: its inner XML is one unit."""
    return el.tag in TEMPLATE_TAGS and len(el) > 0 and is_unit(el.text)


def template_has_text(el: ET.Element) -> bool:
    """Whether a template holds anything to translate: text, or a DisplayName/Unit attribute.

    A template made only of tags (`<saveline Name=… Type=… />`) is no unit: there is nothing
    in it a translator could change."""
    return (bool(strip_marks("".join(el.itertext())).strip())
            or any(c.get(a) for c in el.iter() if c is not el for a in TEMPLATE_TEXT_ATTRS))


def inner_xml(el: ET.Element) -> str:
    """An element's content as XML text, markers removed, unindented like game text."""
    parts = [_esc_text(strip_marks(el.text or ""))]
    parts += [ET.tostring(child, encoding="unicode") for child in el]   # each with its tail
    return unindent(MARKED_ATTR.sub(r"\1", "".join(parts)))


def _compound_note(msgid: str) -> str:
    return ("Compound value: translate only the parts that follow each ▶, keep every ▶ and "
            "everything else (keys, separators) as is.")


def _esc_text(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def _esc_attr(s: str) -> str:
    return (_esc_text(s).replace('"', "&quot;").replace("\n", "&#10;").replace("\t", "&#9;")
            .replace("\r", "&#13;"))


