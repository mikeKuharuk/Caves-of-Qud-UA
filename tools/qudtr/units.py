"""Translation units of the official ExampleLanguage files, and building translated XML from them.

Every translatable thing in `ExampleLanguage/*.example.xml` is marked with '▶': an attribute
value, an element's text, or (in string tables) a `<string>` element. A unit's key is stable
across game builds as long as Freehold does not restructure the element it lives in:

* `<string Context="C" ID="I">` → msgctxt = C (absent when there is no Context), msgid = I
  (the ID *is* the English text and the game's lookup key, whitespace included).
* attribute → msgctxt = element path + "@" + attribute, e.g. `object[Snapjaw]/part[Render]@DisplayName`
* element text → msgctxt = element path, e.g. `topic[name=Quickstart]`

Element paths use each element's *key* attributes, read from the schema that the game writes
into the header comment of every example file (`<tag Name="Key" Value="DisplayText">`). Elements
without keys are positional; the 2nd, 3rd… sibling with the same segment gets '#2', '#3'….

A value with '▶' markers *inside* it is a compound value (alternatives separated by '~', keyed
lists such as `key|▶display,…`, `Faction::▶text`). Its msgid keeps every marker and the
translation must keep them in the same places; the build strips them.

A template (`<description>`, `<leveltext>`, `<template>` with child elements such as `<p>`,
`<stat/>`, `<statline/>`, `<switch>`) is one unit: its msgid is the inner XML with the markers
removed, and the translation is inner XML with the same tags. The game replaces the whole template
with the translated one (Templates.LoadTemplateFromExternal clears the old nodes).
"""
from __future__ import annotations

import collections
import dataclasses
import re
import xml.etree.ElementTree as ET

MARK = "▶"

# Used only for elements the file's schema does not describe (string tables and a few small
# files ship without one). Values that are ▶-marked never count as keys.
FALLBACK_KEYS = ("Name", "ID", "name", "Command", "Class", "Part", "Type", "Code")

# ▶-marked attributes that are really keys or English-only grammar switches. Translating them
# crashes the game or silently breaks grammar (see docs/research/official-framework.md), and the
# Ukrainian provider handles articles itself. They are restated in English when their element
# is written.
EXCLUDED_ATTRS = {
    ("xtagGrammar", "Proper"), ("xtagGrammar", "massNoun"), ("xtagGrammar", "adjunctNounPost"),
    ("xtagGrammar", "iArticle"),
    ("zone", "ProperName"), ("zone", "IndefiniteArticle"), ("zone", "DefiniteArticle"),
    ("part", "BaseHands"), ("part", "Category"),
    # a recipe category the player never sees; CyberneticsSchemasoft and DataDisk compare it
    # with English names written in the code
    ("mod", "TinkerCategory"),
}
EXCLUDED_VALUES = {"true", "false"}
# <tag|stag|property Name="X" Value="▶…">: values that are keys or English grammar, not text.
# The English article logic reads the articles (Translator.IndefiniteArticle); PronounSet names
# a pronoun set (GameObject.GetPropertyOrTag("PronounSet")); TinkerCategory is the recipe
# category above (TinkerItem); DisplayCharacter is the code of a bit type, looked up by the
# codes in recipes (BitType.FetchBitByCode).
EXCLUDED_TAG_NAMES = {"IndefiniteArticle", "DefiniteArticle", "PronounSet", "TinkerCategory",
                      "DisplayCharacter"}

# Roots whose loader merges attribute by attribute (verified: ObjectBlueprintXMLChildNode.Merge),
# so a translated file may contain just the translated attributes. Every other loader is treated
# as "the definition replaces the old one": BookUI, for one, clears a book's pages when the book is
# defined again, and naming lists carry Load="Replace".
SPARSE_ROOTS = {"objects"}

# Elements the game declares as LanguageXml.TemplateElement (2.0.212.31: MutationFactory
# description/leveltext, ActivatedAbilities description, Templates template). A test checks
# that no other ▶-marked element in the real files has child elements.
TEMPLATE_TAGS = frozenset({"description", "leveltext", "template"})
TEMPLATE_NOTE = ("XML template: translate the text and the DisplayName/Unit attributes; keep every "
                 "tag and its other attributes (Name, Value…) as they are. A <stat/> may move within "
                 "its sentence.")
# Inside a template (<p>, <stat/>, <statline/>, <switch>…) only these attributes are text.
TEMPLATE_TEXT_ATTRS = frozenset({"DisplayName", "Unit"})
MARKED_ATTR = re.compile('(=")' + MARK)

BUILD_RE = re.compile(r"\b(\d+\.\d+\.\d+\.\d+)\b")
SCHEMA_TAG = re.compile(r"<([A-Za-z_][\w.-]*)((?:\s+[\w:.-]+=\"[^\"]*\")*)\s*/?>")
SCHEMA_ATTR = re.compile(r"([\w:.-]+)=\"([^\"]*)\"")
GENERATED_MARKER = "Generated by tools/qud.py build"


@dataclasses.dataclass
class Unit:
    file: str                 # example file name, e.g. "Creatures.example.xml"
    msgctxt: str | None
    msgid: str
    kind: str                 # "string" | "attr" | "text" | "template"
    compound: bool = False
    note: str | None = None   # extracted comment for translators

    @property
    def key(self) -> tuple[str | None, str]:
        return (self.msgctxt, self.msgid)


