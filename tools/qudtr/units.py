# One example file

class ExampleFile:
    def __init__(self, xml_text: str, name: str):
        self.text = xml_text
        self.name = name
        self.root = ET.fromstring(xml_text)
        self.schema = parse_schema(xml_text)
        self.build_number = game_build(xml_text)

    # ---- element identity

    def key_names(self, el: ET.Element) -> list[str]:
        names = self.schema.get(el.tag, FALLBACK_KEYS)
        return [a for a in names if el.get(a) is not None and not is_unit(el.get(a))]

    def segment(self, el: ET.Element) -> str:
        parts = [(a, el.get(a)) for a in self.key_names(el)]
        if not parts:
            return el.tag
        if len(parts) == 1 and parts[0][0] == "Name":
            return f"{el.tag}[{parts[0][1]}]"
        return el.tag + "[" + ",".join(f"{a}={v}" for a, v in parts) + "]"

    def child_segments(self, el: ET.Element):
        """Yield (child, segment) with a '#n' suffix for the 2nd+ sibling with the same segment."""
        seen: dict[str, int] = {}
        for child in el:
            if not isinstance(child.tag, str):
                continue  # comments / processing instructions
            seg = self.segment(child)
            seen[seg] = seen.get(seg, 0) + 1
            yield child, seg if seen[seg] == 1 else f"{seg}#{seen[seg]}"

    # ---- extraction

    def string_units(self, el: ET.Element) -> list[Unit]:
        ident = el.get("ID")
        value = el.get("Value")
        english = value if value is not None else unindent(el.text or "")
        if ident is None or not is_unit(english) or not strip_marks(english):
            return []
        compound = is_compound(english)
        # a compound string keeps its markers so the translator sees which parts are text
        msgid = english if compound else ident
        return [Unit(self.name, el.get("Context"), msgid, "string", compound,
                     _compound_note(msgid) if compound else None)]

    def units(self) -> list[Unit]:
        out: list[Unit] = []

        def walk(el: ET.Element, path: list[str]):
            if el.tag == "string":
                out.extend(self.string_units(el))
                return
            here = "/".join(path)
            for attr, value in el.attrib.items():
                if is_unit(value) and not excluded(el.tag, attr, value, el.get("Name")):
                    msgid, compound = _attr_msgid(value)
                    if strip_marks(msgid):   # "▶" alone: nothing to translate (" " is a real value)
                        # our own tables carry a Note attribute for the translator (codetables.py)
                        note = _compound_note(msgid) if compound else el.get("Note")
                        out.append(Unit(self.name, f"{here}@{attr}" if here else f"@{attr}", msgid, "attr",
                                        compound, note))
            if is_template(el) and path:
                if template_has_text(el):
                    out.append(Unit(self.name, here, inner_xml(el), "template", note=TEMPLATE_NOTE))
                return   # nothing inside a template is a unit of its own
            if _has_text_unit(el) and path:
                msgid, compound = _text_msgid(el.text)
                if strip_marks(msgid):
                    out.append(Unit(self.name, here, msgid, "text", compound,
                                    _compound_note(msgid) if compound else None))
            for child, seg in self.child_segments(el):
                walk(child, path + [seg])

        walk(self.root, [])
        return out

    # ---- building

    def build(self, translations: dict, lang: str = "uk", source_note: str = "") -> tuple[str | None, int]:
        """Return (xml, translated_count), or (None, 0) if nothing is translated.

        What gets written:
        * `<string>` entries: only translated ones (each is atomic).
        * `objects` files: only elements that contain a translation. An emitted element carries
          all of its own attributes, untranslated ones in English, so an element-level replace
          (as with xtags) cannot drop a grammar flag.
        * any other file: a top-level entry that contains a translation is written *complete*
          (every attribute, text and child, English where untranslated), because its loader
          may replace the whole definition.
        * positional siblings (two or more same-tag elements without a key, e.g. book pages or
          name syllables) are all-or-nothing, so positions and list lengths never change.
        Untranslated units that are not written fall back to English in the game.
        """
        sparse = self.root.tag in SPARSE_ROOTS

        def render_string(el, indent):
            us = self.string_units(el)
            if not us:
                return None
            t = translations.get(us[0].key)
            if t is None:
                return None
            if us[0].compound:
                t = strip_marks(t)
            attrs = [(k, v) for k, v in el.attrib.items() if k != "Value" and not is_unit(v)]
            attrs.append(("Value", t))
            return indent + "<string " + " ".join(f'{k}="{_esc_attr(v)}"' for k, v in attrs) + " />"

        def render(el, path, indent, complete):
            if el.tag == "string":
                return render_string(el, indent)
            here = "/".join(path)
            own = False
            attrs = []
            for attr, value in el.attrib.items():
                if not is_unit(value):
                    attrs.append((attr, value))
                    continue
                msgid, compound = _attr_msgid(value)
                t = None if excluded(el.tag, attr, value, el.get("Name")) else translations.get(
                    (f"{here}@{attr}" if here else f"@{attr}", msgid))
                if t is not None:
                    own = True
                    attrs.append((attr, strip_marks(t) if compound else t))
                else:
                    attrs.append((attr, strip_marks(value)))
            if is_template(el) and path:
                msgid = inner_xml(el)
                t = translations.get((here, msgid))
                if t is None and not complete:
                    return None
                attr_s = "".join(f' {k}="{_esc_attr(v)}"' for k, v in attrs)
                return f"{indent}<{el.tag}{attr_s}>{msgid if t is None else t}</{el.tag}>"
            text = None
            if _has_text_unit(el) and path:
                msgid, compound = _text_msgid(el.text)
                t = translations.get((here, msgid))
                if t is not None:
                    own = True
                    text = strip_marks(t) if compound else t
                else:
                    text = strip_marks(msgid)
            elif (el.text or "").strip() and complete:
                text = el.text.strip()
            children = render_children(el, path, indent + "  ", complete)
            if not (complete or own or children):
                return None
            attr_s = "".join(f' {k}="{_esc_attr(v)}"' for k, v in attrs)
            if not children and text is None:
                return f"{indent}<{el.tag}{attr_s} />"
            if not children:
                return f"{indent}<{el.tag}{attr_s}>{_esc_text(text)}</{el.tag}>"
            lead = _esc_text(text) if text is not None else ""
            return f"{indent}<{el.tag}{attr_s}>{lead}\n" + "\n".join(children) + f"\n{indent}</{el.tag}>"

        def render_children(el, path, indent, complete):
            items = list(self.child_segments(el))
            out = [render(c, path + [seg], indent, complete) for c, seg in items]
            if not complete:
                positional = collections.Counter(c.tag for c, _ in items if self.segment(c) == c.tag)
                for tag, n in positional.items():
                    idx = [i for i, (c, _) in enumerate(items) if c.tag == tag and self.segment(c) == c.tag]
                    if n >= 2 and any(out[i] is not None for i in idx):
                        for i in idx:
                            c, seg = items[i]
                            out[i] = render(c, path + [seg], indent, True)
            return [r for r in out if r is not None]

        children = []
        for child, seg in self.child_segments(self.root):
            r = render(child, [seg], "  ", False)
            if r is not None and not sparse and child.tag != "string":
                r = render(child, [seg], "  ", True)   # top-level entries are written complete
            if r is not None:
                children.append(r)
        count = len({u.key for u in self.units()} & translations.keys())
        if not count:
            return None, 0
        root_attrs = [("Lang", lang), ("Encoding", "utf-8")] + [
            (k, v) for k, v in self.root.attrib.items() if k not in ("Lang", "Encoding")]
        attr_s = "".join(f' {k}="{_esc_attr(v)}"' for k, v in root_attrs)
        header = (f"<!-- {GENERATED_MARKER} from translations/{lang}/{po_name(self.name)}. "
                  f"Do not edit. {source_note}").rstrip() + " -->"
        body = "\n".join(children)
        return (f'<?xml version="1.0" encoding="utf-8"?>\n{header}\n<{self.root.tag}{attr_s}>\n{body}\n'
                f'</{self.root.tag}>\n'), count

    # ---- reading an existing translated file back

    def read_translation(self, translated_xml: str, skip_identical: bool = True) -> dict:
        """Map units to the values found in a translated file of the same kind.

        The two trees are walked in parallel. A child of the translated file matches an
        example child when the tag and the example child's key attributes agree; among several
        such children (positional siblings like book pages) the n-th matches the n-th. Compound
        units are not read (their ▶ markers cannot be recovered). With `skip_identical`, values
        equal to the English text are ignored, since generated files restate English for
        untranslated units.
        """
        tr_root = ET.fromstring(translated_xml)
        found: dict = {}

        def keep(key, value, english):
            if not (skip_identical and value == english):
                found[key] = value

        if self.root.tag == "strings":
            table = {}
            for el in tr_root.iter("string"):
                value = el.get("Value")
                if value is None:
                    value = unindent(el.text or "")
                table[(el.get("Context"), el.get("ID"))] = value
            for u in self.units():
                if not u.compound and u.key in table:
                    keep(u.key, table[u.key], u.msgid)
            return found

        def walk(ex_el, tr_el, path):
            here = "/".join(path)
            for attr, value in ex_el.attrib.items():
                if is_unit(value) and not excluded(ex_el.tag, attr, value, ex_el.get("Name")):
                    msgid, compound = _attr_msgid(value)
                    if not compound and tr_el.get(attr) is not None:
                        keep((f"{here}@{attr}" if here else f"@{attr}", msgid), tr_el.get(attr), msgid)
            if is_template(ex_el) and path:
                msgid, value = inner_xml(ex_el), inner_xml(tr_el)
                if value:
                    keep((here, msgid), value, msgid)
                return
            if _has_text_unit(ex_el) and path and (tr_el.text or "").strip():
                msgid, compound = _text_msgid(ex_el.text)
                if not compound:
                    keep((here, msgid), unindent(tr_el.text), msgid)
            occurrence = collections.Counter()
            for child, seg in self.child_segments(ex_el):
                sig = (child.tag, tuple((a, child.get(a)) for a in self.key_names(child)))
                occurrence[sig] += 1
                candidates = [c for c in tr_el if c.tag == child.tag and all(c.get(a) == v for a, v in sig[1])]
                if len(candidates) >= occurrence[sig]:
                    walk(child, candidates[occurrence[sig] - 1], path + [seg])

        walk(self.root, tr_root, [])
        return found


